export function tieneIcono(nombre: string): boolean {
  return iconos.has(nombre);
}

/** El icono de lucide de un nombre del catálogo; si no existe, el de por defecto. */
export function iconoDe(nombre: string): LucideIcon {
  return iconos.get(nombre) ?? (iconos.get(iconoPorDefecto) as LucideIcon);
}

